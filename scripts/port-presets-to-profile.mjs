// Re-home the stand's agent presets into the profile (DSH 0.1.7). Idempotent.
//
//   node port-presets-to-profile.mjs [--check]
//
// WHY. Up to 0.1.6 a custom preset was a DIRECTORY under `~/.dsh/.agent-presets`
// holding `preset.yml` (name, description, order) and `agent.cordis.yml` (the
// plugin list), discovered by the host: `packages/preset/agent-presets/src/
// discovery.ts:51`, `USER_PRESET_DIR = '.agent-presets'`. DSH 0.1.7 replaced
// that package with `agent-preset` + `agent-preset-registry` and dropped the
// directory mechanism outright - the strings `.agent-presets`, `preset.yml`,
// `agent.cordis.yml` and `USER_PRESET` appear nowhere in the 0.1.7 tree. A
// preset is now one profile row:
//
//   - id: preset-<id>
//     name: '@deepseek-ai/dsh-agent-preset'
//     config: { id, name, description, order, plugins: [...] }
//
// so the stand's presets vanished from the mode menu on the upgrade, and the
// profile's `agent-presets` row (the default selector) pointed at a package
// that no longer exists.
//
// WHAT THIS DOES. Writes each preset directory into the profile patch as such a
// row, between markers, and repoints the default selector at the new registry
// id. Nothing is re-based: the shipped `standard` preset is IDENTICAL in 0.1.6
// and 0.1.7 (parsed and compared field by field), so the presets built on top of
// it carry over unchanged.
//
// The `agent.cordis.yml` text is copied verbatim, only indented: it carries
// comments and `!!js` tags that a YAML round-trip would lose.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const DSH = process.env.DSH_HOME ?? `${process.env.HOME}/.dsh`;
const PRESETS = join(DSH, '.agent-presets');
const PATCH = join(DSH, 'profiles/web/cordis.patch.yml');
const CHECK = process.argv.includes('--check');

const BEGIN = '# >>> dsh-local: stand presets (generated by scripts/port-presets-to-profile.mjs)';
const END = '# <<< dsh-local: stand presets';

// A module name in a preset used to resolve against the PRESET directory; an
// inserted row resolves it against the directory of the patch FILE
// (`anchorInsertedPluginNames`, app-boot/src/index.ts:346). The files stay where
// they are - only the route to them is rewritten.
const TO_PROFILE = '../../.agent-presets';

const yamlScalar = (s) => JSON.stringify(String(s));

function presetRow(dir) {
  const meta = Object.fromEntries(
    readFileSync(join(PRESETS, dir, 'preset.yml'), 'utf8')
      .split('\n')
      .filter((l) => /^[a-z]+:/.test(l))
      .map((l) => [l.slice(0, l.indexOf(':')), l.slice(l.indexOf(':') + 1).trim()]),
  );
  // ONE pass over both forms. Two chained replaces are wrong: the first turns
  // `./x.mjs` into a path that STARTS with `../`, which the second then prefixes
  // a second time (`../../.agent-presets/../.agent-presets/...`).
  const body = readFileSync(join(PRESETS, dir, 'agent.cordis.yml'), 'utf8')
    .replace(/^(\s*name:\s*)(\.\.?)\/(\S+)/gm, (_m, head, dots, rest) =>
      `${head}${TO_PROFILE}/${dots === '.' ? `${dir}/` : ''}${rest}`)
    .split('\n')
    .map((l) => (l.trim() === '' ? '' : '          ' + l))
    .join('\n')
    .replace(/\n+$/, '');
  // Under `insert:`, not as a bare row. A top-level `- id: …` in a patch list is
  // an id-targeted OVERRIDE of an existing entry; when no such entry exists it is
  // only a per-entry Loader warning and nothing is added (app-boot/src/index.ts:354
  // walks `patch.insert` alone). That is why the first attempt changed nothing and
  // the mode menu still offered the four shipped presets.
  return [
    `    - id: preset-${dir}`,
    `      name: '@deepseek-ai/dsh-agent-preset'`,
    `      config:`,
    `        id: ${dir}`,
    ...(meta.name ? [`        name: ${yamlScalar(meta.name)}`] : []),
    ...(meta.description ? [`        description: ${yamlScalar(meta.description)}`] : []),
    ...(meta.order ? [`        order: ${meta.order}`] : []),
    `        plugins:`,
    body,
  ].join('\n');
}

if (!existsSync(PRESETS)) { console.log(`no ${PRESETS} - nothing to port`); process.exit(0); }
const dirs = readdirSync(PRESETS, { withFileTypes: true })
  .filter((e) => e.isDirectory() && existsSync(join(PRESETS, e.name, 'agent.cordis.yml')))
  .map((e) => e.name)
  .sort();
if (dirs.length === 0) { console.log(`no presets in ${PRESETS}`); process.exit(0); }

let s = readFileSync(PATCH, 'utf8');

// The default selector moved with the package: `agent-presets` -> the registry
// row the web bundle inserts (packages/bundle/web-app/cordis.patch.yml:559).
const before = s;
s = s.replace(/^- id: agent-presets$/m, '- id: agent-preset-registry');

const block = [BEGIN, '- insert:', ...dirs.map(presetRow), END].join('\n');
const marked = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
s = marked.test(s) ? s.replace(marked, block) : `${s.replace(/\n*$/, '\n')}\n${block}\n`;

if (CHECK) {
  const ok = s === readFileSync(PATCH, 'utf8');
  console.log(ok ? `presets: ${dirs.join(', ')} - up to date` : 'presets: profile is OUT OF DATE, run without --check');
  process.exit(ok ? 0 : 1);
}
writeFileSync(PATCH, s);
console.log(`${PATCH}: ${dirs.length} preset(s) written (${dirs.join(', ')})${before === s ? '' : ''}`);
